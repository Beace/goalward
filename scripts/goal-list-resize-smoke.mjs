import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'

const output = 'test-results/goal-list-resize'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const results = []
const title = '生成一篇如何做好业务品质的 html 文档并补充质量诊断依据和完整验收标准'
try {
  for (const [width, height] of [[1536, 960], [1280, 720]]) for (const reducedMotion of ['no-preference', 'reduce']) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:1420')
    const list = page.getByRole('complementary', { name: '目标列表' })
    const handle = page.getByRole('separator', { name: '调整目标列表宽度' })
    const sidebar = page.getByRole('navigation', { name: '工作空间导航' })
    const size = async () => (await list.boundingBox()).width
    const sidebarSize = async () => (await sidebar.boundingBox()).width
    await page.getByRole('button', { name: '创建目标', exact: true }).first().click()
    await page.locator('#goal-title').fill(title)
    await page.locator('#goal-expected').fill('生成品质改进文档，保留诊断依据与验收记录')
    await page.getByRole('dialog').getByRole('button', { name: '创建目标', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[data-dialog-exit]'))
    if (await page.locator('[data-sonner-toast] [data-close-button]').count()) await page.locator('[data-sonner-toast] [data-close-button]').click()
    await expect(page.locator('[data-sonner-toast]')).toHaveCount(0)
    await page.getByRole('button', { name: '创建任务', exact: true }).click()
    await page.locator('#task-title').fill('岛台石材选择')
    await page.getByRole('dialog').getByRole('button', { name: '创建任务', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[data-dialog-exit]'))
    if (await page.locator('[data-sonner-toast] [data-close-button]').count()) await page.locator('[data-sonner-toast] [data-close-button]').click()
    await page.getByRole('navigation', { name: '工作空间导航' }).getByRole('button', { name: /^目标/ }).click()
    const taskAlignment = await page.locator('.goal-task-row').first().evaluate(row => {
      const icon = row.children[0].getBoundingClientRect()
      const link = row.children[1].querySelector('button').getBoundingClientRect()
      return { horizontalGap: link.left - icon.right, centerDelta: Math.abs(icon.top + icon.height / 2 - (link.top + link.height / 2)), paddingLeft: getComputedStyle(row.children[1].querySelector('button')).paddingLeft }
    })
    expect(taskAlignment.horizontalGap).toBeCloseTo(10, 0)
    expect(taskAlignment.centerDelta).toBeLessThan(1)
    expect(taskAlignment.paddingLeft).toBe('0px')
    const initial = await size(), outerInitial = await sidebarSize()
    await page.screenshot({ path: `${output}/${width}-${reducedMotion}-initial.png` })
    let box = await handle.boundingBox()
    const x = box.x + box.width / 2, y = box.y + 180
    await page.mouse.move(x, y)
    await expect(handle).toHaveAttribute('data-separator', 'hover')
    await page.mouse.down()
    for (const delta of [30, 90, 45, 110]) {
      await page.mouse.move(x + delta, y, { steps: 4 })
      expect(Math.abs(await size() - initial - delta)).toBeLessThan(2)
      expect(await sidebarSize()).toBeCloseTo(outerInitial, 0)
    }
    await page.mouse.up()
    const remembered = await size()
    await sidebar.getByRole('button', { name: /^任务/ }).click()
    await sidebar.getByRole('button', { name: /^目标/ }).click()
    expect(await size()).toBeCloseTo(remembered, 0)
    await sidebar.getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('button', { name: '返回工作台' }).click()
    expect(await size()).toBeCloseTo(remembered, 0)
    await handle.focus()
    await page.keyboard.press('Home')
    expect(await size()).toBeCloseTo(180, 0)
    await expect(handle).toBeFocused()
    const text = await list.locator('.goal-choice > span').evaluate(el => ({ right: el.getBoundingClientRect().right, parentRight: el.closest('aside').getBoundingClientRect().right, clamp: getComputedStyle(el).webkitLineClamp, height: el.clientHeight, scroll: el.scrollHeight }))
    expect(text.right).toBeLessThanOrEqual(text.parentRight)
    expect(text.clamp).toBe('2')
    expect(text.scroll).toBeGreaterThan(text.height)
    await page.keyboard.press('ArrowRight')
    expect(await size()).toBeGreaterThan(180)
    await page.keyboard.press('End')
    expect(await size()).toBeCloseTo(360, 0)
    await page.getByRole('separator', { name: '调整侧边栏宽度', exact: true }).focus()
    await page.keyboard.press('End')
    expect(await sidebarSize()).toBeCloseTo(420, 0)
    await expect.poll(size).toBeCloseTo(360, 0)
    expect((await page.locator('.goal-detail').boundingBox()).width).toBeGreaterThanOrEqual(480)
    await page.screenshot({ path: `${output}/${width}-${reducedMotion}-both-wide.png` })
    if (width === 1280) {
      expect(await page.locator('.goal-columns').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(1)
      await page.setViewportSize({ width: 1100, height: 720 })
      await expect.poll(async () => (await page.locator('.goal-detail').boundingBox()).width).toBeGreaterThanOrEqual(480)
      expect(await size()).toBeGreaterThanOrEqual(180)
      expect(await page.locator('.goal-detail').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
      await page.screenshot({ path: `${output}/1100-${reducedMotion}.png` })
      await page.setViewportSize({ width, height })
    }
    await handle.focus()
    await page.keyboard.press('Home')
    box = await handle.boundingBox()
    await handle.evaluate(el => el.addEventListener('pointermove', e => { el.dataset.pointerId = String(e.pointerId) }))
    await page.mouse.move(box.x, y)
    await page.mouse.down()
    await page.mouse.move(box.x + 45, y, { steps: 4 })
    await handle.evaluate(el => el.dispatchEvent(new PointerEvent('pointercancel', { bubbles: true, pointerId: Number(el.dataset.pointerId), pointerType: 'mouse' })))
    const cancelled = await size()
    await page.mouse.move(box.x + 85, y, { steps: 4 })
    expect(await size()).toBeCloseTo(cancelled, 0)
    await expect(handle).not.toHaveAttribute('data-separator', 'active')
    await page.mouse.up()
    box = await handle.boundingBox()
    await page.mouse.move(box.x, y)
    await page.mouse.down()
    await page.mouse.move(box.x + 20, y, { steps: 4 })
    expect(await size()).toBeCloseTo(cancelled + 20, 0)
    await page.evaluate(() => window.dispatchEvent(new Event('blur')))
    const blurred = await size()
    await page.mouse.move(box.x + 50, y, { steps: 4 })
    expect(await size()).toBeCloseTo(blurred, 0)
    await page.mouse.up()
    await list.getByRole('textbox', { name: '搜索目标' }).fill('不存在的目标')
    await expect(list.locator('.goal-choice')).toHaveCount(0)
    await list.getByRole('textbox', { name: '搜索目标' }).fill('品质')
    await expect(list.locator('.goal-choice')).toHaveCount(1)
    await list.locator('.goal-choice').click()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
    results.push({ width, height, reducedMotion, initial, taskAlignment, checks: ['task icon and title alignment', '1:1 drag and rapid reversal', 'outer sidebar independent', 'width remembered after navigation and settings', 'keyboard min/max and focus', 'two-line title truncation', 'both panels widened', 'detail responsive to available width', 'pointercancel and next drag', 'blur ends drag', 'search and selection', 'no horizontal overflow'], errors })
    await page.close()
  }
  await writeFile(`${output}/qa.json`, JSON.stringify(results, null, 2))
  console.log(JSON.stringify(results, null, 2))
} finally { await browser.close() }
